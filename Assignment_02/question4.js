
var marks = parseInt(prompt("Enter total marks out of 100:"));

if (marks >= 90) {
    console.log("Grade: A");
} else if (marks >= 85) {
    console.log("Grade: A-");
} else if (marks >= 80) {
    console.log("Grade: B+");
} else if (marks >= 75) {
    console.log("Grade: B");
} else if (marks >= 70) {
    console.log("Grade: B-");
} else if (marks >= 65) {
    console.log("Grade: C+");
} else if (marks >= 60) {
    console.log("Grade: C");
} else if (marks >= 55) {
    console.log("Grade: C-");
} else if (marks >= 50) {
    console.log("Grade: D");
} else {
    console.log("Grade: F");
}

